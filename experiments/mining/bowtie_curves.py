# ---- group-law generation on w^2 = q(r): the parabola through three points meets the curve in a fourth rational point
import itertools
def qcoeffs(i, a2, b2):
    txt = subprocess.run(["gp", "-q"], input=f"print(Vec({quartic(i, a2, b2)}));", capture_output=True, text=True).stdout
    return [Fr(x) for x in re.findall(r"-?\d+(?:/\d+)?", txt)]          # leading first
def qval(c, x): v = Fr(0); [v := v * x + k for k in c]; return v
def fourth(c, P, Q, R):
    (x1, y1), (x2, y2), (x3, y3) = P, Q, R
    if len({x1, x2, x3}) < 3: return None
    # parabola y = a x^2 + b x + d through the three points
    det = (x1 - x2) * (x1 - x3) * (x2 - x3)
    a = (x3 * (y2 - y1) + x2 * (y1 - y3) + x1 * (y3 - y2)) / det
    b = (x3**2 * (y1 - y2) + x2**2 * (y3 - y1) + x1**2 * (y2 - y3)) / det
    d = (x2 * x3 * (x2 - x3) * y1 + x3 * x1 * (x3 - x1) * y2 + x1 * x2 * (x1 - x2) * y3) / det
    lead = c[0] - a * a
    if lead == 0: return None
    # q(x) - (a x^2 + b x + d)^2 = lead (x - x1)(x - x2)(x - x3)(x - x4): compare x^3 coefficients
    c3 = c[1] - 2 * a * b
    x4 = -c3 / lead - x1 - x2 - x3
    return (x4, a * x4 * x4 + b * x4 + d)
