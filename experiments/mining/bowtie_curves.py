def quartic(i, a2, b2):
    X = coord[2 * i]; Y = coord[2 * i + 1]
    fx = f"(({X[0]})+({X[1]})*r+({X[2]})*r^2)"; fy = f"(({Y[0]})+({Y[1]})*r+({Y[2]})*r^2)"
    vx, vy = f"({b2})", f"({-a2})"
    return f"9*({fx}*{vx}^2+{fy}*{vy}^2)^2 - 12*({vx}^3+{vy}^3)*({fx}^2*{vx}+{fy}^2*{vy})"
def bowtie(s, r, i, a2, b2):
    R = raw(s, r); G = 0
    for x, y in R: G = gcd(G, gcd(x, y))
    pts = [(x // G, y // G) for x, y in R]; n = pts[0][0]**3 + pts[0][1]**3
    if any(gcd(p, q) != 1 or p == 0 or q == 0 for p, q in pts): return ("triple not coprime", n)
    x, y = pts[i]; vx, vy = b2, -a2
    A = vx**3 + vy**3; B = 3 * (x * vx * vx + y * vy * vy); C = 3 * (x * x * vx + y * y * vy); D = B * B - 4 * A * C
    w = isqrt(D) if D >= 0 else -1
    if w < 0 or w * w != D: return ("not square", n)
    out = []
    for t in (Fr(-B + w, 2 * A), Fr(-B - w, 2 * A)):
        X, Y = x + t * vx, y + t * vy
        if X.denominator != 1 or Y.denominator != 1: return ("second line rational, not integral", n)
        out.append((int(X), int(Y)))
    if any(gcd(p, q) != 1 or p == 0 or q == 0 for p, q in out): return ("second line not coprime", n)
    return ("BOWTIE", abs(n))
